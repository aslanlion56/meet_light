export const MESSAGE_TYPES = {
  MEETING_STATE: 'MEETING_STATE',
  MEETING_INFO: 'MEETING_INFO',
  HOST_READY: 'HOST_READY',
  PIN_SERIAL_TAB: 'PIN_SERIAL_TAB',
  RECONNECT: 'RECONNECT',
  GET_STATUS: 'GET_STATUS',
  MANUAL_LED: 'MANUAL_LED',
  RESTORE_LED: 'RESTORE_LED',
  CLOUD_STATUS: 'CLOUD_STATUS',
  CLOUD_SYNC: 'CLOUD_SYNC',
  CLOUD_UNLINK: 'CLOUD_UNLINK',
  PING: 'PING'
};

/** @deprecated Use MESSAGE_TYPES.RECONNECT */
export const LEGACY_MESSAGE_TYPES = {
  CONNECT_ARDUINO: 'CONNECT_ARDUINO',
  OPEN_SERIAL_SETUP: 'OPEN_SERIAL_SETUP',
  RECONNECT_NOW: 'RECONNECT_NOW',
  SERIAL_STATUS: 'SERIAL_STATUS',
  SERIAL_CONNECT: 'SERIAL_CONNECT',
  AUTO_CONNECT: 'AUTO_CONNECT',
  REQUEST_PORT_CONNECT: 'REQUEST_PORT_CONNECT',
  LED_STATE: 'LED_STATE'
};

export function normalizeMessageType(type) {
  if (type === LEGACY_MESSAGE_TYPES.RECONNECT_NOW) {
    return MESSAGE_TYPES.RECONNECT;
  }
  if (
    type === LEGACY_MESSAGE_TYPES.CONNECT_ARDUINO ||
    type === LEGACY_MESSAGE_TYPES.OPEN_SERIAL_SETUP
  ) {
    return MESSAGE_TYPES.RECONNECT;
  }
  return type;
}
